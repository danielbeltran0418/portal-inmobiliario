import { test, expect } from '@playwright/test'
import { clienteAdmin } from '../rls/ayudantes'
test('los planes no inventan tarifas y el checkout permanece cerrado',async ({page})=>{
  await page.goto('/planes')
  await expect(page.getByRole('heading',{name:'Básico',exact:true})).toBeVisible()
  await expect(page.getByText('Por definir',{exact:true})).toHaveCount(2)
  await page.screenshot({path:'test-results/proptech-planes.png',fullPage:true})
  await page.getByText('Anual',{exact:true}).click()
  await expect(page.getByLabel('Anual',{exact:true})).toBeChecked()
  await page.getByRole('link',{name:'Ver disponibilidad'}).first().click()
  await expect(page).toHaveURL(/periodo=anual/)
  await expect(page.getByRole('button',{name:/Preparar/})).toBeDisabled()
})
test('en móvil abre filtros, conserva decimales y permite quitar el máximo',async ({page})=>{
  const { data }=await clienteAdmin().from('barrios').select('slug').eq('activo',true).limit(1).single()
  if(!data) throw new Error('Falta barrio')
  await page.setViewportSize({width:390,height:844})
  await page.goto('/'+data.slug)
  await page.getByRole('button',{name:'Filtros',exact:true}).click()
  const dialogo=page.getByRole('dialog')
  await dialogo.getByLabel('Precio mínimo',{exact:true}).fill('45000000.25')
  await dialogo.getByLabel('Precio máximo',{exact:true}).fill('90000000.75')
  await dialogo.getByLabel('Precio máximo',{exact:true}).fill('')
  await dialogo.getByRole('button',{name:'Filtrar',exact:true}).click()
  await expect(page).toHaveURL(/precio_min=45000000.25/)
  expect(new URL(page.url()).searchParams.has('precio_max')).toBe(false)
  await expect(dialogo).toHaveCount(0)
  await page.getByRole('button',{name:'Filtros',exact:true}).click()
  await page.getByRole('dialog').getByRole('link',{name:'Limpiar filtros',exact:true}).click()
  await expect(page).toHaveURL(new RegExp('/'+data.slug+'$'))
  await page.getByRole('button',{name:'Filtros',exact:true}).click()
  await expect(page.getByRole('dialog').getByLabel('Precio mínimo',{exact:true})).toHaveValue('')
  await expect(page.getByRole('dialog').getByLabel('Precio máximo',{exact:true})).toHaveValue('')
  await page.keyboard.press('Escape')
  await page.screenshot({path:'test-results/proptech-movil.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})